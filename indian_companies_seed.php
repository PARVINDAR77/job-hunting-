    \App\Models\Company::create([
        'name'           => $c[0],
        'logo'           => 'https://ui-avatars.com/api/?name='.urlencode($c[0]).'&color=7F9CF5&background=EBF4FF&bold=true',
        'description'    => 'A leading '.$c[1].' company based in '.$c[2].', India. We are committed to excellence, innovation, and creating meaningful career opportunities.',
        'industry'       => $c[1],
        'location'       => $c[2],
        'website'        => $c[4],
        'employee_count' => $c[3],
    ]);
    $count++;
}
echo "Inserted {$count} real Indian companies.\n";

\App\Models\Job::factory(1500)->create();

$skills = \App\Models\Skill::all();
if ($skills->count() > 0) {
    \App\Models\Job::all()->each(function($job) use ($skills) {
        $job->skills()->sync($skills->random(rand(2,5))->pluck('id')->toArray());
    });
}
echo "1500 jobs created and skills attached!\n";
exit;

